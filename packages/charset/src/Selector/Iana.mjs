function normalizeRecord(raw) {
  const name = raw[NAME];
  const aliasList = raw[ALIAS_LIST];
  const preferredName = raw[PREFERRED_NAME] ?? name;

  return {
    [NAME]: name,
    [MIB_ENUM]: raw[MIB_ENUM],
    [PREFERRED_NAME]: preferredName,
    [ALIAS_LIST]: aliasList.includes(name)
      ? [...aliasList]
      : [name, ...aliasList],
  };
}

const IANA_RECORD_LIST = Object.freeze(
  [...RAW_RECORD_LIST]
    .sort((left, right) => left[MIB_ENUM] - right[MIB_ENUM])
    .map(normalizeRecord),
);

